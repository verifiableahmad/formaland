"""formaland CLI.

    formaland prove      build the Lean spec; fail on any sorry/extra axiom
    formaland gen        export the registries and generate CVL, Halmos and mutants
    formaland halmos     run Halmos on the reference targets (and mutants with --mutants),
                         or on the targets named
    formaland cvl-check  type-check the generated CVL locally (no API key)
    formaland all        prove, gen, halmos --mutants, cvl-check
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from . import cvl, halmos, ir, mutants

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"
BUILD = ROOT / "build"
ALLOWED_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


@dataclass(frozen=True)
class Target:
    """A contract the properties are checked against. `deploy` is the body of
    the Halmos `_deploy()` hook; `imports` maps symbol -> source path."""

    name: str
    std: str
    imports: dict[str, str]
    deploy: str
    mutant: mutants.Mutant | None = None


@dataclass(frozen=True)
class Reference:
    """The reference implementation of a standard, which Certora proves."""

    std: str
    target: str
    files: list[str]
    link: list[str] = field(default_factory=list)


def _erc20_target(name: str, path: str, m: mutants.Mutant | None = None) -> Target:
    return Target(name, "erc20", {name: path}, f"return address(new {name}());", m)


def _vault_target(name: str, path: str, m: mutants.Mutant | None = None) -> Target:
    return Target(name, "erc4626",
                  {name: path, "Asset": "contracts/harness/Asset.sol",
                   "IERC20": "@openzeppelin/contracts/token/ERC20/IERC20.sol"},
                  f"asset = address(new Asset());\nreturn address(new {name}(IERC20(asset)));", m)


def _mutant_target(m: mutants.Mutant) -> Target:
    make = _erc20_target if m.std == "erc20" else _vault_target
    return make(mutants.contract_name(m), f"contracts/mutants/{mutants.contract_name(m)}.sol", m)


TARGETS = [
    _erc20_target("OZToken", "contracts/harness/OZToken.sol"),
    _vault_target("OZVault", "contracts/harness/OZVault.sol"),
    *[_mutant_target(m) for m in mutants.MUTANTS],
]
REFERENCES = [
    Reference("erc20", "OZToken", ["contracts/harness/OZToken.sol:OZToken"]),
    Reference("erc4626", "OZVault",
              ["contracts/harness/OZVault.sol:OZVault", "contracts/harness/Asset.sol:Asset"],
              ["OZVault:_asset=Asset"]),
]
# The theorem `prove` audits for each standard.
REGISTRIES = {
    "erc20": "Formaland.ERC20.registry_holds",
    "erc4626": "Formaland.ERC4626.registry_holds",
}


def registry(std: str) -> Path:
    return BUILD / f"{std}.json"


def sh(cmd: list[str], cwd: Path = ROOT, capture: bool = False) -> subprocess.CompletedProcess:
    print(f"$ {' '.join(cmd)}", file=sys.stderr)
    return subprocess.run(cmd, cwd=cwd, check=True, text=True, capture_output=capture)


def tool(name: str) -> str:
    venv = ROOT / ".venv/bin" / name
    return str(venv) if venv.exists() else (shutil.which(name) or name)


def axioms(out: str) -> set[str] | None:
    """Parses `#print axioms` output; None if it is not recognised."""
    if "does not depend on any axioms" in out:
        return set()
    if "depends on axioms: [" not in out:
        return None
    inner = out.split("depends on axioms: [", 1)[1].split("]", 1)[0]
    return {a.strip() for a in inner.split(",") if a.strip()}


def cmd_prove(_: argparse.Namespace) -> int:
    sh(["lake", "build"], cwd=SPEC)
    audit = SPEC / ".lake/Audit.lean"
    status = 0
    for thm in REGISTRIES.values():
        audit.write_text(f"import Formaland\n#print axioms {thm}\n")
        out = sh(["lake", "env", "lean", str(audit)], cwd=SPEC, capture=True).stdout
        used = axioms(out)
        if used is None or used - ALLOWED_AXIOMS:
            print(f"{thm}: non-standard axioms or unreadable audit:\n{out}", file=sys.stderr)
            status = 1
        else:
            print(f"{thm}: proved (axioms: {', '.join(sorted(used)) or 'none'})")
    return status


def _target_test(t: Target) -> str:
    base = halmos.base_name(ir.STANDARDS[t.std])
    imports = "".join(f'import {{{sym}}} from "{path if path.startswith("@") else "../" + path}";\n'
                      for sym, path in t.imports.items())
    return (
        "// SPDX-License-Identifier: MIT\n// GENERATED by `formaland gen`. Do not edit.\n"
        "pragma solidity ^0.8.20;\n\n"
        f'import {{{base}}} from "./generated/{base}.sol";\n'
        f"{imports}\n"
        f"contract {t.name}Spec is {base} {{\n"
        "    function _deploy() internal override returns (address) {\n"
        + "".join(f"        {line}\n" for line in t.deploy.splitlines())
        + "    }\n}\n"
    )


def cmd_gen(_: argparse.Namespace) -> int:
    BUILD.mkdir(exist_ok=True)
    (ROOT / "test/generated").mkdir(parents=True, exist_ok=True)
    mutants.write_all(ROOT)
    for std_name in REGISTRIES:
        out = sh(["lake", "exe", "export", std_name], cwd=SPEC, capture=True).stdout
        registry(std_name).write_text(out)
        std, specs = ir.load(str(registry(std_name)))
        source = str(registry(std_name).relative_to(ROOT))
        upper = std_name.upper()

        (ROOT / f"certora/specs/{upper}.spec").write_text(cvl.spec_file(std, specs, source))
        for ref in (r for r in REFERENCES if r.std == std_name):
            conf = cvl.conf(std, ref.files, ref.target, f"certora/specs/{upper}.spec", ref.link)
            (ROOT / f"certora/conf/{ref.target}.conf").write_text(json.dumps(conf, indent=4) + "\n")

        (ROOT / f"test/generated/{halmos.base_name(std)}.sol").write_text(halmos.test_file(std, specs, source))
        targets = [t for t in TARGETS if t.std == std_name]
        for t in targets:
            (ROOT / f"test/{t.name}.t.sol").write_text(_target_test(t))
        print(f"{std_name}: {len(specs)} properties -> certora/specs/{upper}.spec, "
              f"test/generated/{halmos.base_name(std)}.sol, {len(targets)} targets")
    return 0


# Halmos exit codes per test.
PASS, FAIL, TIMEOUT = 0, 1, 2


def run_halmos(target: str) -> dict[str, int]:
    """Returns test name -> Halmos exit code."""
    out_json = BUILD / f"halmos-{target}.json"
    out_json.unlink(missing_ok=True)
    r = subprocess.run([tool("halmos"), "--contract", f"{target}Spec", "--json-output", str(out_json)],
                       cwd=ROOT, text=True, capture_output=True)
    if not out_json.exists():
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
        return {}
    results = json.loads(out_json.read_text())["test_results"]
    tests = next(v for k, v in results.items() if k.endswith(f"{target}Spec"))
    return {t["name"].split("(")[0]: t["exitcode"] for t in tests}


def cmd_halmos(args: argparse.Namespace) -> int:
    status = 0
    for t in TARGETS:
        if args.targets and t.name not in args.targets:
            continue
        if t.mutant and not args.mutants and not args.targets:
            continue
        _, specs = ir.load(str(registry(t.std)))
        res = run_halmos(t.name)
        print(f"\n== {t.name}")
        failed, inconclusive = [], []
        for sp in specs:
            check, reach = res.get(halmos.check_name(sp)), res.get(halmos.reach_name(sp))
            if check is None or reach is None:
                verdict = "MISSING"
            elif check == FAIL:
                verdict = "FAIL"  # a counterexample, whatever the reach twin says
            elif reach == PASS:
                verdict = "VACUOUS"  # the reach twin found no path
            elif check == TIMEOUT:
                verdict = "TIMEOUT"
            elif reach == TIMEOUT:
                verdict = "UNKNOWN"  # passed, but reachability is unconfirmed
            else:
                verdict = "pass"
            if verdict in ("FAIL", "MISSING", "VACUOUS"):
                failed.append(sp.id)
            elif verdict != "pass":
                inconclusive.append(sp.id)
            print(f"  {verdict:8} {sp.id}")
        if t.mutant is None:
            # A timeout is not a failure, but it is not a pass either: say so.
            if failed:
                status = 1
            if inconclusive:
                print(f"  -> {len(inconclusive)} inconclusive (Lean proof and Certora still apply)")
        else:
            killed = bool(failed)
            unexpected = sorted(set(failed) - set(t.mutant.expect))
            survived = "SURVIVED" + (f" ({len(inconclusive)} inconclusive)" if inconclusive else "")
            print(f"  -> {'killed' if killed else survived}"
                  + (f"; also failed: {', '.join(unexpected)}" if unexpected else ""))
            if not killed:
                status = 1
    return status


def solc() -> str:
    """solc on PATH, else the one Foundry downloaded for foundry.toml's version."""
    if shutil.which("solc"):
        return shutil.which("solc")
    svm = Path.home() / "Library/Application Support/svm/0.8.30/solc-0.8.30"
    if not svm.exists():
        svm = Path.home() / ".svm/0.8.30/solc-0.8.30"
    # certoraRun splits the path on spaces ("Application Support"), so link it.
    link = BUILD / "solc"
    if not link.exists():
        link.symlink_to(svm)
    return str(link)


def cmd_cvl_check(_: argparse.Namespace) -> int:
    """Compiles each reference and type-checks its CVL locally; proving needs CERTORAKEY."""
    status = 0
    for ref in REFERENCES:
        r = subprocess.run([tool("certoraRun"), f"certora/conf/{ref.target}.conf", "--solc", solc(),
                            "--compilation_steps_only"],
                           cwd=ROOT, text=True, capture_output=True)
        print(f"\n== {ref.target}: {'ok' if r.returncode == 0 else 'FAILED'}")
        if r.returncode:
            sys.stdout.write(r.stdout[-3000:])
            sys.stderr.write(r.stderr[-3000:])
            status = 1
    return status


def cmd_all(args: argparse.Namespace) -> int:
    args.mutants, args.targets = True, []
    for step in (cmd_prove, cmd_gen, cmd_halmos, cmd_cvl_check):
        if step(args):
            return 1
    return 0


def main() -> None:
    p = argparse.ArgumentParser(prog="formaland")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("prove").set_defaults(fn=cmd_prove)
    sub.add_parser("gen").set_defaults(fn=cmd_gen)
    h = sub.add_parser("halmos")
    h.add_argument("--mutants", action="store_true")
    h.add_argument("targets", nargs="*", help="only these targets (e.g. OZVault)")
    h.set_defaults(fn=cmd_halmos)
    sub.add_parser("cvl-check").set_defaults(fn=cmd_cvl_check)
    sub.add_parser("all").set_defaults(fn=cmd_all)
    args = p.parse_args()
    sys.exit(args.fn(args))


if __name__ == "__main__":
    main()
