"""Certora CVL backend: one rule per exported property.

Arithmetic is `mathint`, which matches the Lean model's unbounded naturals.
Certora starts every rule from arbitrary storage, which matches `State.WF`.
Vacuity is checked by the prover's `rule_sanity` option (see the .conf).
"""

from __future__ import annotations

from typing import Any

from .ir import Read, Spec, Standard, _tag, all_reads, read_of

RESERVED = {"from"}


def ident(name: str) -> str:
    if name == "self":
        return "currentContract"
    return name + "_" if name in RESERVED else name


def term(sp: Spec, node: Any) -> str:
    tag, body = _tag(node)
    if tag == "var":
        return ident(body["name"])
    if tag == "lit":
        return str(body["n"])
    if tag == "maxUint":
        return "max_uint256"
    if tag == "obs":
        return read_of(sp.std, body).name
    if tag == "ret":
        return "ret"
    if tag == "add":
        return f"({term(sp, body['a'])} + {term(sp, body['b'])})"
    if tag == "mul":
        return f"({term(sp, body['a'])} * {term(sp, body['b'])})"
    raise ValueError(tag)


OPS = {"eq": "==", "ne": "!=", "lt": "<", "le": "<="}


def formula(sp: Spec, node: Any) -> str:
    tag, body = _tag(node)
    if tag == "tt":
        return "true"
    if tag in OPS:
        return f"{term(sp, body['a'])} {OPS[tag]} {term(sp, body['b'])}"
    if tag == "and":
        return f"{formula(sp, body['p'])} && {formula(sp, body['q'])}"
    if tag == "implies":
        return f"({formula(sp, body['p'])} => {formula(sp, body['q'])})"
    raise ValueError(tag)


def _read_stmt(sp: Spec, r: Read) -> str:
    d = sp.std.obs[r.obs]
    on = "" if d.on == "self" else f"{d.on}."
    args = ", ".join(ident(a) for a in r.args)
    return f"    mathint {r.name} = {on}{d.fn}({args});"


def rule(sp: Spec) -> str:
    params = ["env e", "address caller"] + [
        f"{'address' if t == 'addr' else 'uint256'} {ident(n)}" for n, t in sp.vars
    ]
    cd = sp.call_def
    call = f"{cd.fn}@withrevert({', '.join(['e'] + [ident(a) for a in sp.call[1]])})"
    lines = [
        f"/// {sp.id}",
        f"/// intent: {sp.intent}",
        f"rule {sp.ident}({', '.join(params)}) {{",
        "    require e.msg.sender == caller;",
        "    require e.msg.value == 0;",
        *[_read_stmt(sp, r) for r in all_reads(sp, "pre")],
    ]
    if sp.pre != "tt":
        lines.append(f"    require {formula(sp, sp.pre)};")
    if sp.uses_ret():
        lines.append(f"    {cd.returns} ret_raw = {call};")
    else:
        lines.append(f"    {call};")
    lines.append("    bool reverted = lastReverted;")
    if sp.uses_ret():
        lines.append("    mathint ret = " + ("ret_raw ? 1 : 0;" if cd.returns == "bool" else "ret_raw;"))
    lines += [_read_stmt(sp, r) for r in all_reads(sp, "post")]
    if sp.kind == "ensures":
        lines.append(f"    assert !reverted => ({formula(sp, sp.post)});")
    elif sp.kind == "revertsIf":
        lines.append("    assert reverted;")
    elif sp.kind == "succeedsIf":
        lines.append("    assert !reverted;")
    lines.append("}")
    return "\n".join(lines)


def _abi(arg_count: int) -> str:
    return ", ".join(["address"] * arg_count)


def header(std: Standard, source: str) -> str:
    out = [
        f"// GENERATED by `formaland gen` from {source}. Do not edit.",
        f"// Source of truth: {std.lean} (all rules proved there).",
        "",
    ]
    out += [f"using {c} as {k};" for k, c in std.contracts.items()]
    if std.contracts:
        out.append("")
    out.append("methods {")
    for d in std.obs.values():
        qual = "" if d.on == "self" else f"{std.contracts[d.on]}."
        entry = f"    function {qual}{d.fn}({_abi(len(d.args))}) external returns (uint256) envfree;"
        if entry not in out:
            out.append(entry)
    for c in std.calls.values():
        out.append(f"    function {c.fn}({', '.join(c.types)}) external returns ({c.returns});")
    out.append("}")
    return "\n".join(out) + "\n"


def spec_file(std: Standard, specs: list[Spec], source: str) -> str:
    return header(std, source) + "\n" + "\n\n".join(rule(sp) for sp in specs) + "\n"


def conf(std: Standard, files: list[str], contract: str, spec_path: str,
         link: list[str] = ()) -> dict[str, Any]:
    c: dict[str, Any] = {
        "files": files,
        "verify": f"{contract}:{spec_path}",
        "packages": ["@openzeppelin/contracts=lib/openzeppelin-contracts/contracts"],
        "rule_sanity": "basic",
        "optimistic_loop": False,
        "msg": f"formaland {std.name} on {contract}",
    }
    if link:
        c["link"] = list(link)
    return c
